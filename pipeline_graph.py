from typing import Annotated, Any, Dict, List, Optional
from langchain_core.messages import BaseMessage
from langgraph.graph.message import add_messages
from typing_extensions import TypedDict
from QuerySpec import QuerySpec


class AgentState(TypedDict):
  # 1. CONVERSATION CONTEXT & INPUT (Node 0)
  user_question: str  # Raw user query (e.g. "What about last month?")
  standalone_question: str  # Rewritten self-contained question from Node 0
  chat_history: Annotated[
      List[BaseMessage], add_messages
  ]  # Multi-turn history

  # 2. SEMANTIC QUERY SPECIFICATION (Node 1)
  query_spec: QuerySpec  # The central Pydantic QuerySpec object

  # 3. SCHEMA & VALUE LINKING (Node 2)
  linked_tables: List[str]  # Candidate tables from ChromaDB
  linked_schema_ddl: str  # Pruned CREATE TABLE statements for Node 7
  db_lookup_results: Dict[
      str, List[str]
  ]  # Matches found in MySQL (e.g. Acme -> Acme Corp)

  # 4. AMBIGUITY & CLARIFICATION (Nodes 3, 4, 5, 6)
  is_confident: bool  # True if 0 ambiguities (fast-path to Node 7)
  clarification_needed: bool  # True if Node 4 needs to interrupt
  user_choices: Dict[
      str, str
  ]  # User options captured by interrupt() resume

  # 5. SQL GENERATION & EXECUTION (Nodes 7, 8, 9, 10)
  raw_sql: str  # MySQL 8.0 SELECT string generated by Node 7
  sql_error: Optional[str]  # Error traceback if AST validator or DB fails
  retry_count: int  # Retry counter for self-correction loop (max 3)
  query_results: Optional[
      List[Dict[str, Any]]
  ]  # Rows returned by safe execution

  # 6. FINAL PRESENTATION (Node 11)
  final_response: str  # Natural language explanation + markdown table
  next_node: Optional[str]  # Internal routing tag


from langgraph.graph import StateGraph, START, END
from langgraph.checkpoint.memory import MemorySaver

# 1. Import all node functions from your files
from contextlaoder_Node_0 import conversation_context_node  # Node 0
from Node_1 import intent_extractor_node  # Node 1
from Node_2 import schema_linker_node  # Node 2
from ambiguity_detector import ambiguity_detector_node  # Node 3
from Node_4 import clarification_node  # Node 4
from Node_5 import (
    pass_through_node,
    route_after_ambiguity_detector,
)  # Node 5 & Router
from Node_6 import spec_resolver_node  # Node 6
# 2. Initialize the StateGraph with your AgentState
workflow = StateGraph(AgentState)
# 3. Add all the Nodes
workflow.add_node("context_loader", conversation_context_node)  # Node 0
workflow.add_node("intent_extractor", intent_extractor_node)  # Node 1
workflow.add_node("schema_linker", schema_linker_node)  # Node 2
workflow.add_node("ambiguity_detector", ambiguity_detector_node)  # Node 3
workflow.add_node("clarification_node", clarification_node)  # Node 4
workflow.add_node("pass_through_node", pass_through_node)  # Node 5
workflow.add_node("spec_resolver", spec_resolver_node)  # Node 6
# 4. Add Linear Edges (Node 0 -> Node 1 -> Node 2 -> Node 3)
workflow.add_edge(START, "context_loader")
workflow.add_edge("context_loader", "intent_extractor")
workflow.add_edge("intent_extractor", "schema_linker")
workflow.add_edge("schema_linker", "ambiguity_detector")
# 5. Add the Conditional Edge (Branching after Node 3)
workflow.add_conditional_edges(
    "ambiguity_detector",
    route_after_ambiguity_detector,  # Decision function from Node_5.py
    {
        "clarification_node": "clarification_node",  # If ambiguous -> Node 4
        "pass_through_node": "pass_through_node",  # If clear -> Node 5
    },
)
# 6. Edge from Node 4 (Interrupt/Resume) -> Node 6 (Spec Resolver)
workflow.add_edge("clarification_node", "spec_resolver")
# 7. Edge from Node 6 and Node 5 -> (Destination: Node 7 / END for now)
# Once Node 7 is built:
# workflow.add_edge("pass_through_node", "sql_generator")
# workflow.add_edge("spec_resolver", "sql_generator")
# For now, end the sub-graph test at END:
workflow.add_edge("pass_through_node", END)
workflow.add_edge("spec_resolver", END)
# 8. Compile with MemorySaver checkpointer (enables interrupt() pausing!)
app = workflow.compile(checkpointer=MemorySaver())

